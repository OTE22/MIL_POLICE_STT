import { strict as assert } from "node:assert";
import { test } from "node:test";
import { readFile, mkdir, writeFile } from "node:fs/promises";
import { createServer } from "vite";

async function loadCatalogue() {
  return { ...JSON.parse(await readFile("../backend/app/assets/html_statement.json", "utf8")),
    note: JSON.parse(await readFile("../backend/app/assets/html_note.json", "utf8")) };
}

test("repeatable Arabic HTML masks preserve independent fields, source order and escaped text", async () => {
  const server = await createServer({ server: { middlewareMode: true, hmr: false, watch: null } });
  try {
    const lib = await server.ssrLoadModule("/src/lib/html-report.ts");
    const catalogue = await loadCatalogue();
    const first = lib.newStatement(); first.values.statement_name = "الاسم الأول";
    first.entries[0].answer = "لم أشاهد الشخص المذكور.";
    const second = lib.newStatement(); second.values.statement_name = "الاسم الثاني";
    second.entries[0].answer = '<script>alert("test")</script> & نص ثانٍ';
    const document = { revision: catalogue.revision, subject: "اختبار HTML", investigator_id: null, blocks: [first, second] };
    const session = { session_number: "TEST-HTML", title: "جلسة تجريبية", investigators: [] };
    const html = lib.renderHtmlReport(document, catalogue, session, { highlight: true });
    assert.equal((html.match(/<section class="statement-block"/g) || []).length, 2);
    assert.ok(html.indexOf("الاسم الأول") < html.indexOf("الاسم الثاني"));
    assert.ok(html.includes("[اسم الأب]"));
    assert.ok(html.includes("لم أشاهد الشخص المذكور."));
    assert.ok(!html.includes("<script>"));
    assert.ok(html.includes("&lt;script&gt;"));
    assert.ok(!html.includes(catalogue.clauses.attestation));
    assert.ok(!html.includes("غير محكوم سابقاً"));
    const approved = lib.renderHtmlReport({ ...document, blocks: [{ ...first, attestation_confirmed: true }] }, catalogue, session);
    assert.ok(approved.includes(catalogue.clauses.attestation));
    assert.equal(lib.newStatement().values.statement_name, undefined);

    const person = "person-a";
    const qa = { id: "qa-1", included_in_report: true, answer_speaker_id: person, report_question_text: "أين كنت؟", report_answer_text: "في المنزل",
      question_source_text: "وين كنت؟", answer_source_text: "بالبيت", source_segment_ids: ["segment-1"], source_recording_ids: ["recording-1"], start_seconds: 1.84, end_seconds: 9.6 };
    const imported = lib.importAnswers({ ...lib.newStatement(), speaker_id: person }, [qa, { ...qa, id: "other", answer_speaker_id: "person-b" }]);
    assert.equal(imported.entries.length, 1);
    assert.equal(lib.importAnswers(imported, [qa]).entries.length, 1, "reimport does not duplicate text");
    assert.deepEqual(imported.entries[0].source_snapshot[0].source_segment_ids, ["segment-1"]);
    const payload = lib.editableDocument({ ...document, blocks: [imported] });
    assert.equal(payload.blocks[0].entries[0].source_snapshot, undefined);
    assert.deepEqual(payload.blocks[0].entries[0].source_block_ids, ["qa-1"]);
    const withSources = lib.renderHtmlReport({ ...document, blocks: [imported] }, catalogue, session, { showSources: true });
    assert.ok(withSources.includes("1.840–9.600"));

    // A standalone blank mask for review, generated by the same production renderer.
    const font = await readFile("public/fonts/NotoNaskhArabic-Regular.ttf");
    const blankStatements = [lib.newStatement(), lib.newStatement()].map(block => ({ ...block, identity_checked: true, attestation_confirmed: true,
      entries: [lib.newEntry(), lib.newEntry(), lib.newEntry()] }));
    const blank = lib.renderHtmlReport({ ...document, subject: "قالب إفادة — الحقول المتغيرة", blocks: blankStatements }, catalogue, session,
      { highlight: true, fontDataUrl: `data:font/ttf;base64,${font.toString("base64")}` });
    for (const field of catalogue.fields) assert.ok(blank.includes(`data-field="${field.key}"`), `mask marks ${field.key}`);
    await mkdir("../../storage/model-evaluation/results/html-statement", { recursive: true });
    await writeFile("../../storage/model-evaluation/results/html-statement/blank-mask.html", blank, "utf8");
  } finally { await server.close(); }
});

test("notes mix with statements in order, keep independent fields and export the seven-variable mask", async () => {
  const server = await createServer({ server: { middlewareMode: true, hmr: false, watch: null } });
  try {
    const lib = await server.ssrLoadModule("/src/lib/html-report.ts");
    const catalogue = await loadCatalogue();
    const first = lib.newNote(), second = lib.newNote(), statement = lib.newStatement();
    first.values = { note_date: "24/10/2026", note_time: "13:30", note_text: "لم ترد نتيجة الفحص بعد.\nسطر إضافي.", clerk_name: "كاتب أول" };
    second.values.note_text = '<img src=x onerror="alert(1)"> & ملاحظة ثانية';
    assert.notEqual(first.id, second.id);
    assert.equal(second.values.clerk_name, undefined);
    const session = { session_number: "TEST-NOTES", title: "جلسة تجريبية", investigators: [{ id: "investigator", rank: "رتبة", full_name: "محقق تجريبي" }] };
    const document = { revision: catalogue.revision, subject: "محضر تجريبي", investigator_id: "investigator", blocks: [first, statement, second] };
    const original = JSON.stringify(document);
    const html = lib.renderHtmlReport(document, catalogue, session, { highlight: true });
    assert.deepEqual([...html.matchAll(/data-block-id="([^"]+)"/g)].map(m => m[1]), [first.id, statement.id, second.id]);
    assert.equal((html.match(/class="statement-block note-block"/g) || []).length, 2);
    assert.ok(html.includes("لم ترد نتيجة الفحص بعد.\nسطر إضافي."));
    assert.ok(html.includes("24/10/2026") && html.includes("13:30"));
    assert.ok(html.includes("ملاحظة:") && html.includes("كاتب أول"));
    assert.ok(html.includes("رتبة محقق تجريبي"));
    assert.ok(!html.includes("<img"));
    assert.ok(html.includes("&lt;img src=x onerror=&quot;alert(1)&quot;&gt; &amp;"));
    assert.equal(JSON.stringify(document), original, "rendering cannot change stored content");
    const payload = lib.editableDocument(document);
    assert.deepEqual(payload.blocks[0], first);
    assert.equal(payload.blocks[0].entries, undefined, "notes do not become speaker answers");
    const reordered = lib.renderHtmlReport({ ...document, blocks: [second, first, statement] }, catalogue, session);
    assert.deepEqual([...reordered.matchAll(/data-block-id="([^"]+)"/g)].map(m => m[1]), [second.id, first.id, statement.id]);

    const font = await readFile("public/fonts/NotoNaskhArabic-Regular.ttf");
    const options = { highlight: true, fontDataUrl: `data:font/ttf;base64,${font.toString("base64")}` };
    const blankNotes = [lib.newNote(), lib.newNote()];
    const blank = lib.renderHtmlReport({ ...document, subject: "قالب ملاحظة — الحقول المتغيرة", investigator_id: null, blocks: blankNotes }, catalogue, session, options);
    for (const field of catalogue.note.fields) assert.ok(blank.includes(`[${field.label}]`), `note mask marks ${field.key}`);
    assert.ok(!blank.includes("س.ج"));
    assert.ok(!blank.includes("اسكندر") && !blank.includes("البندقية"));
    const folder = "../../storage/model-evaluation/results/html-statement";
    await mkdir(folder, { recursive: true });
    await writeFile(`${folder}/blank-note-mask.html`, blank, "utf8");
    const mixed = lib.renderHtmlReport({ ...document, subject: "إفادات وملاحظات — نموذج فارغ", investigator_id: null,
      blocks: [lib.newStatement(), blankNotes[0], lib.newStatement(), blankNotes[1]] }, catalogue, session, options);
    await writeFile(`${folder}/mixed-report-mask.html`, mixed, "utf8");
  } finally { await server.close(); }
});
